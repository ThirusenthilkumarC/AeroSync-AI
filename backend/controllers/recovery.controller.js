import { sendSuccess, sendError } from '../utils/responseHandler.js';
import { 
  getRecoveryPlansService, getRecoveryPlanByIdService, generateRecoveryPlansService, 
  approveRecoveryPlanService, rejectRecoveryPlanService, getExplanationService, 
  validateConstraintsService, autoReplanService, getDecisionReplayService 
} from '../services/recovery.service.js';

export const getRecoveryPlans = async (req, res, next) => {
  try {
    const plans = await getRecoveryPlansService();
    return sendSuccess(res, plans, 'Recovery plans list retrieved');
  } catch (err) {
    return next(err);
  }
};

export const getRecoveryPlanById = async (req, res, next) => {
  try {
    const plan = await getRecoveryPlanByIdService(req.params.id);
    if (!plan) return sendError(res, 'Recovery plan not found', 404);
    return sendSuccess(res, plan, 'Recovery plan details retrieved');
  } catch (err) {
    return next(err);
  }
};

export const generateRecovery = async (req, res, next) => {
  try {
    const newPlans = await generateRecoveryPlansService(req.body);
    return sendSuccess(res, newPlans, 'Recovery plans V1, V2, and V3 generated by Autonomous Solver', 201);
  } catch (err) {
    return next(err);
  }
};

export const approveRecovery = async (req, res, next) => {
  try {
    const result = await approveRecoveryPlanService(req.params.id, req.body?.notes);
    return sendSuccess(res, result, 'Recovery plan authorized by operator');
  } catch (err) {
    return next(err);
  }
};

export const rejectRecovery = async (req, res, next) => {
  try {
    const result = await rejectRecoveryPlanService(req.params.id, req.body?.reason);
    return sendSuccess(res, result, 'Recovery plan rejected by operator');
  } catch (err) {
    return next(err);
  }
};

